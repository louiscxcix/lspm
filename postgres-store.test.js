const {test}=require('node:test');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const {Pool}=require('pg');
const {withPostgresStore}=require('./postgres-store');
const Projects=require('./projects');
const Model=require('./ontology-model');
const {importBackup}=require('./import-backup');

test('PostgreSQL: transactions, project projections, history, imports, isolation and concurrent writes', {skip:!process.env.TEST_DATABASE_URL}, async t=>{
  const pool=new Pool({connectionString:process.env.TEST_DATABASE_URL,max:4});
  t.after(()=>pool.end());
  const alice=randomUUID(),bob=randomUUID();
  const use=async (user,fn)=>{const client=await pool.connect();try{return await withPostgresStore(client,user,fn);}finally{client.release();}};
  let ws=await use(alice,s=>s.load());
  assert.equal(ws.revision,0);
  ws.projects.push(Projects.create('LS'),Projects.create('Other'));
  ws=await use(alice,s=>s.save(ws,null,ws.revision));
  const part=Model.addEntity(ws.library,{type:'Part',name:'G65'});
  const step=Model.addEntity(ws.library,{type:'Production Step',name:'Router'});
  ws=await use(alice,s=>s.save(ws,'library',ws.revision));
  for(let i=0;i<ws.projects.length;i++){const p=ws.projects[i];p.entities.push({...part,projectId:p.id},{...step,projectId:p.id});ws=await use(alice,s=>s.save(ws,p.id,ws.revision));}
  const projectId=ws.projects[0].id;
  ws.projects[0].entities.find(e=>e.id===step.id).plannedStart='2026-10-16';
  ws.projects[0].entities.find(e=>e.id===part.id).name='G65 revised';
  ws=await use(alice,s=>s.save(ws,projectId,ws.revision));
  assert.equal(ws.projects[1].entities.find(e=>e.id===part.id).name,'G65 revised');
  assert.equal(ws.projects[1].entities.find(e=>e.id===step.id).plannedStart,undefined);
  assert.equal(ws.projects[0].entities.find(e=>e.id===step.id).plannedStart,'2026-10-16');
  const history=await use(alice,s=>s.listChanges('library'));
  assert.ok(history.changes.length);
  ws=await use(alice,s=>s.revertChange(ws.pendingChange.id,ws.revision));
  assert.equal(ws.library.entities.find(e=>e.id===part.id).name,'G65');
  ws=await use(alice,s=>s.saveWip({projectId,revision:ws.revision,capturedAt:'2026-10-16T12:00:00Z',filename:'mes.xlsx',sheet:'WIP',rows:[{row:1,column:2,partName:'G65',partId:part.id,stage:'Router',quantity:0}]}));
  assert.equal((await use(alice,s=>s.listWip(projectId))).counts[0].quantity,0);
  ws=await use(alice,s=>s.revertChange(ws.pendingChange.id,ws.revision));
  assert.equal((await use(alice,s=>s.listWip(projectId))).snapshots.length,0);
  await use(alice,s=>s.putSettings(projectId,'production',{zoom:1.5}));
  assert.equal((await use(alice,s=>s.load())).viewSettings[projectId].production.zoom,1.5);
  const job=await use(alice,s=>s.saveIngestion({filename:'note.txt',mimeType:'text/plain',content:Buffer.from('original bytes'),scope:'library',draft:{objects:[],relationships:[]}}));
  const exported=await use(alice,s=>s.exportAll());
  assert.equal(Buffer.from(exported.sources[0].content,'base64').toString(),'original bytes');
  assert.equal(exported.ingestionJobs[0].id,job.jobId);
  const bobWorkspace=await use(bob,s=>s.load());
  assert.deepEqual(bobWorkspace.projects,[]);
  await assert.rejects(use(bob,s=>s.listWip(projectId)),/Unknown project/);
  // RLS also prevents cross-owner foreign-key references with guessed IDs.
  await assert.rejects(use(bob,(_,client)=>client.query('INSERT INTO pm.project_memberships(project_id,entity_id) VALUES ($1,$2)',[projectId,part.id])),/foreign key/);
  const current=await use(alice,s=>s.load());
  const results=await Promise.allSettled([use(alice,s=>s.save(current,projectId,current.revision)),use(alice,s=>s.save(current,projectId,current.revision))]);
  assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
  assert.match(results.find(r=>r.status==='rejected').reason.message,/STALE_REVISION/);
  assert.equal((await use(alice,s=>s.load())).revision,current.revision+1);
  const restored=await use(bob,(store,client)=>importBackup(store,client,exported));
  assert.equal(restored.projects.length,2);
  assert.equal(restored.library.entities.find(e=>e.id===part.id).name,'G65');
  const copied=await use(bob,s=>s.exportAll());
  assert.deepEqual(copied.sources,exported.sources);
  assert.deepEqual(copied.changeSets,exported.changeSets);
  await assert.rejects(use(bob,(store,client)=>importBackup(store,client,exported)),/empty account/);
  const carol=randomUUID(),broken=structuredClone(exported);
  broken.memberships[0].entity_id='missing';
  await assert.rejects(use(carol,(store,client)=>importBackup(store,client,broken)),/foreign key|Missing|missing|Unknown|membership/i);
  assert.equal((await use(carol,s=>s.load())).projects.length,0);
});
