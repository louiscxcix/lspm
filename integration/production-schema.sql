-- Additive: this schema never alters PM tables or Supabase Auth settings.
CREATE SCHEMA IF NOT EXISTS production;
REVOKE ALL ON SCHEMA production FROM PUBLIC;

CREATE TABLE IF NOT EXISTS production.meta (
    key TEXT PRIMARY KEY, value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS production.catalog (
    kind TEXT NOT NULL, code TEXT NOT NULL, line_code TEXT NOT NULL,
    data_json TEXT NOT NULL, PRIMARY KEY(kind,code,line_code)
);
CREATE TABLE IF NOT EXISTS production.reports (
    id TEXT PRIMARY KEY, date TEXT NOT NULL, line_code TEXT NOT NULL,
    model_code TEXT NOT NULL, unit TEXT NOT NULL,
    revision INTEGER NOT NULL DEFAULT 0, data_json TEXT NOT NULL,
    finalized INTEGER NOT NULL DEFAULT 0 CHECK (finalized IN (0,1)),
    payload_json TEXT, content_hash TEXT, workbook BYTEA,
    UNIQUE(date,line_code,model_code,unit)
);
CREATE TABLE IF NOT EXISTS production.uploads (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id TEXT NOT NULL UNIQUE REFERENCES production.reports(id),
    payload_json TEXT NOT NULL, content_hash TEXT NOT NULL, uploaded_at TEXT NOT NULL
);

CREATE OR REPLACE FUNCTION production.prevent_frozen_change() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    IF OLD.finalized = 1 THEN
        RAISE EXCEPTION 'Finalized reports are immutable' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE OR REPLACE FUNCTION production.prevent_upload_change() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    RAISE EXCEPTION 'Uploads are immutable' USING ERRCODE = '23514';
END;
$$;
REVOKE ALL ON FUNCTION production.prevent_frozen_change() FROM PUBLIC;
REVOKE ALL ON FUNCTION production.prevent_upload_change() FROM PUBLIC;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='production_frozen' AND tgrelid='production.reports'::regclass) THEN
        CREATE TRIGGER production_frozen BEFORE UPDATE OR DELETE ON production.reports
            FOR EACH ROW EXECUTE FUNCTION production.prevent_frozen_change();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='production_upload_frozen' AND tgrelid='production.uploads'::regclass) THEN
        CREATE TRIGGER production_upload_frozen BEFORE UPDATE OR DELETE ON production.uploads
            FOR EACH ROW EXECUTE FUNCTION production.prevent_upload_change();
    END IF;
END $$;

-- Browser anon/authenticated roles receive no access to these tables.
ALTER TABLE production.meta ENABLE ROW LEVEL SECURITY;
ALTER TABLE production.catalog ENABLE ROW LEVEL SECURITY;
ALTER TABLE production.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE production.uploads ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA production FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA production FROM PUBLIC;
INSERT INTO production.meta VALUES ('schemaVersion','1') ON CONFLICT DO NOTHING;
